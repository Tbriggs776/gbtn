export function inGreatVibes(cp: number): boolean {
  let lo = 0;
  let hi = GREAT_VIBES_CODEPOINTS.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = GREAT_VIBES_CODEPOINTS[mid];
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}
